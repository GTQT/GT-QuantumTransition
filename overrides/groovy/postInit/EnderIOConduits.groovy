// Older Core builds already provide the plate and its processing recipes.
if (oreDict.getItems('plateCrudeSteel').isEmpty()) {
    def crudeSteelPlate = item('placeholdername:crude_steel_plate')
    oreDict.add('plateCrudeSteel', crudeSteelPlate)

    recipemap('bender').recipeBuilder()
        .inputs(ore('ingotCrudeSteel'))
        .circuitMeta(1)
        .outputs(crudeSteelPlate)
        .duration(98)
        .EUt(24)
        .buildAndRegister()
}

